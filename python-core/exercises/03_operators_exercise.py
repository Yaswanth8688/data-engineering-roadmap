# Exercise: Operators

# 1. Pick two numbers and apply all arithmetic operators to them.
# 2. Compare the two numbers using all comparison operators.
# 3. Combine two conditions using "and" and "or".

a = 15
b = 4

print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)
print("a // b =", a // b)
print("a % b =", a % b)
print("a ** b =", a ** b)

print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)

print("(a > 10) and (b < 10):", (a > 10) and (b < 10))
print("(a < 10) or (b < 10):", (a < 10) or (b < 10))
