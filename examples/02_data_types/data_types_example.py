# Data Types example

age = 30                # Integer
height = 5.9            # Float
is_active = True         # Boolean
name = "Yaswanth"      # String
scores = [90, 85, 92]   # List

print(type(age), age)
print(type(height), height)
print(type(is_active), is_active)
print(type(name), name)
print(type(scores), scores)

# Convert between data types
age_str = str(age)
print("Age as string:", age_str)
