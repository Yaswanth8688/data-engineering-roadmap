# Operators example

a = 8
b = 3

# Arithmetic operators
print('a + b =', a + b)
print('a - b =', a - b)
print('a * b =', a * b)
print('a / b =', a / b)
print('a // b =', a // b)
print('a % b =', a % b)
print('a ** b =', a ** b)

# Comparison operators
print('a == b:', a == b)
print('a != b:', a != b)
print('a > b:', a > b)
print('a < b:', a < b)

# Logical operators
print('(a > 5) and (b > 1):', (a > 5) and (b > 1))
print('(a > 5) or (b > 10):', (a > 5) or (b > 10))
print('not (a == b):', not (a == b))
